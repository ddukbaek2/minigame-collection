//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import { Vector2 } from "../libs/vanilla.js/src/base/vector2.js";
import { Pivot } from "../libs/vanilla.js/src/base/pivot.js";
import { WorldNode } from "../libs/vanilla.js/src/core/node/worldnode.js";


//==============================================================================
// 파트 식별자.
//==============================================================================
export const PartId = {
	intro: "intro",
	title: "title",
	games: "games",
	achievement: "achievement",
	configuration: "configuration",
	dailyMission: "dailyMission",
	minesweeper: "minesweeper",
};


//==============================================================================
// 파트 베이스 클래스.
// - 컨텐트 영역에 자식으로 들어가서 활성/비활성으로 켜고 끈다.
//==============================================================================
export class Part extends WorldNode {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { import("./main.js").MainScene } */ #app;
	/** @private @type { boolean } */ #isBuilt;

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {
		super();
		this.setPivot(Pivot.topLeft);
		this.setAnchor(Pivot.topLeft);
		this.setLocalPosition(Vector2.zero());
		this.setActive(false);
		this.#app = null;
		this.#isBuilt = false;
	}

	//==============================================================================
	// 앱(메인 씬) 설정.
	//==============================================================================
	setApp(app) {
		this.#app = app;
	}

	//==============================================================================
	// 앱(메인 씬) 반환.
	//==============================================================================
	getApp() {
		return this.#app;
	}

	//==============================================================================
	// 식별자.
	//==============================================================================
	getPartId() {
		return "";
	}

	//==============================================================================
	// 네비게이션 타이틀.
	//==============================================================================
	getNavigationTitle() {
		return "";
	}

	//==============================================================================
	// 네비게이션 사용 여부.
	//==============================================================================
	hasNavigation() {
		return true;
	}

	//==============================================================================
	// 최초 1회 빌드.
	//==============================================================================
	build() {
		if (this.#isBuilt) {
			return;
		}
		this.#isBuilt = true;
		this.onBuild();
	}

	//==============================================================================
	// 자식 클래스에서 오버라이드 하여 노드 구성.
	//==============================================================================
	/** @virtual */
	onBuild() {
	}

	//==============================================================================
	// 활성화 진입. (showPart에서 호출)
	//==============================================================================
	/** @virtual */
	enter() {
	}

	//==============================================================================
	// 비활성화. (showPart에서 호출)
	//==============================================================================
	/** @virtual */
	exit() {
	}

	//==============================================================================
	// 컨텐트 사이즈가 변경됨.
	//==============================================================================
	/** @virtual */
	onResize() {
	}
}
